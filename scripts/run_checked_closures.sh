#!/usr/bin/env bash
# Real checked inputs only. Synthetic AST unit tests do not count as acceptance.
set -euo pipefail
cd "$(dirname "$0")/.."
root=$PWD
compiler_repo=$(realpath "${IDRIC_REPO:-.idric}")
out=$(realpath -m "${IDRIC_X86_CLOSURE_ARTIFACTS_DIR:-build/checked-closures}")
pin=29420f7e5a954ba0a66f622f0311298f823fbfff
baseline=e4018340efed6a2cdb296ea62caaca231fd97004
test "$(git -C "$compiler_repo" rev-parse HEAD)" = "$pin"
mkdir -p "$out"
printf 'compiler\t%s\nbackend\t%s\nbaseline\t%s\n' "$pin" "$(git rev-parse HEAD)" "$baseline" > "$out/revisions.tsv"
# The reduced callback is generated first, exactly as in compiler PR #158.
for name in OrderedClosure OrderedDirect OrderedNamed ReversedClosure CapturedClosure ConstructorCallbacks; do
  source="$root/fixtures/closures/$name.idric"
  "$compiler_repo/_/edric" --emit-one-step "$source" -o "$out/$name.one-step"
  "$compiler_repo/_/edric" --emit-one-step "$source" -o "$out/$name.repeat.one-step"
  cmp "$out/$name.one-step" "$out/$name.repeat.one-step"
done
file_source="$compiler_repo/examples/autogenerated/native-binary-file-read/BinaryFilePrefix.idric"
"$compiler_repo/_/edric" --emit-one-step "$file_source" -o "$out/BinaryFilePrefix.one-step"
"$compiler_repo/_/edric" --emit-one-step "$file_source" -o "$out/BinaryFilePrefix.repeat.one-step"
cmp "$out/BinaryFilePrefix.one-step" "$out/BinaryFilePrefix.repeat.one-step"
# Prove that the real callback did not optimize away the requested mechanism.
grep -F '<OrderedClosure.{main:0} underapp 2>()' "$out/OrderedClosure.one-step"
grep -F ' @ (' "$out/OrderedClosure.one-step"
sha256sum "$out"/*.one-step > "$out/artifacts.sha256"

# Baseline and candidate are fed identical bytes, not substitutes.
old=$(mktemp -d)
trap 'git worktree remove --force "$old" >/dev/null 2>&1 || true; rmdir "$old" 2>/dev/null || true' EXIT
git worktree add --detach "$old" "$baseline"
status=0
PYTHONPATH="$root" python3 scripts/check_process_arguments.py "$compiler_repo" "$out/process-arguments" || status=1
while read -r name expected; do
  source="$root/fixtures/closures/$name.idric"
  if ! python3 -m backend.idric_x86 "$out/$name.one-step" --source "$source" \
    -o "$out/$name.elf" --listing "$out/$name.instructions" \
    --run-receipt "$out/$name.execution" --expect-stdout-hex "$expected" \
    > "$out/$name.linux.log" 2>&1; then
    cat "$out/$name.linux.log" >&2; status=1; continue
  fi
  if ! python3 -m backend.idric_x86 "$out/$name.one-step" --source "$source" \
    -o "$out/$name.repeat.elf" --listing "$out/$name.repeat.instructions" ||
    ! cmp "$out/$name.elf" "$out/$name.repeat.elf" ||
    ! cmp "$out/$name.instructions" "$out/$name.repeat.instructions"; then
    status=1
  fi
  if ! python3 -m backend.idric_x86 "$out/$name.one-step" --source "$source" \
    --target netbsd-x86_64 -o "$out/$name.netbsd.elf" --listing "$out/$name.netbsd.instructions" ||
    ! readelf -h -l -n "$out/$name.netbsd.elf" > "$out/$name.netbsd.readelf" ||
    ! grep -F 'NetBSD' "$out/$name.netbsd.readelf"; then
    status=1
  fi
  printf '%s expected_stdout_hex=%s\n' "$name" "$expected"
  cat "$out/$name.execution"
done <<'CASES'
OrderedClosure 4142
OrderedDirect 4142
OrderedNamed 4142
ReversedClosure 4241
CapturedClosure 4142
ConstructorCallbacks 215859414241435a442e
CASES

# Verify that the executable case actually projected all three constructor shapes.
for constructor in Both One Quiet; do
  grep -F "ConstructorCallbacks.$constructor constructor_match" "$out/ConstructorCallbacks.instructions"
done
# Structural and native receipt checks are distinct from the compiler frontier.
# Compare old and new on the original checked file artifact for each target.
for target in linux-x86_64 netbsd-x86_64; do
  for implementation in baseline candidate; do
    if [[ $implementation == baseline ]]; then backend="$old"; else backend="$root"; fi
    (
      cd "$backend"
      python3 - "$out/BinaryFilePrefix.one-step" "$file_source" "$target" "$out" "$implementation" <<'PY'
import hashlib
import sys
from pathlib import Path
from backend.idric_x86 import (
    ArtifactError, UnsupportedError, compile_artifact, parse_checked_artifact,
)
artifact, source, target, directory, implementation = sys.argv[1:]
directory = Path(directory)
prefix = directory / f"file-{implementation}-{target}"
parsed = parse_checked_artifact(Path(artifact))
assert len(parsed.definitions) == 158, len(parsed.definitions)
output = prefix.with_suffix(".elf")
output.unlink(missing_ok=True)
try:
    compile_artifact(Path(artifact), output, prefix.with_suffix(".listing"),
                     Path(source), target=target)
except (ArtifactError, UnsupportedError) as error:
    assert not output.exists()
    result = f"REJECTED\t{error.code}\t{error.detail}"
else:
    result = "COMPILED_NOT_RUN\tno file semantics claimed"
prefix.with_suffix(".tsv").write_text(
    f"artifact_sha256\t{parsed.sha256}\ndefinitions\t{len(parsed.definitions)}\n"
    f"target\t{target}\nimplementation\t{implementation}\nresult\t{result}\n"
    "native_file_operations\tNOT_VERIFIED\nnetbsd_native_execution\tNOT_RUN\n")
print(prefix.with_suffix(".tsv").read_text(), end="")
PY
    ) || status=1
  done
done
# Compare the callback against the old backend too.
if (cd "$old"; python3 -m backend.idric_x86 "$out/OrderedClosure.one-step" \
       --source "$root/fixtures/closures/OrderedClosure.idric" \
       -o "$out/OrderedClosure.baseline.elf") > "$out/OrderedClosure.baseline.log" 2>&1; then
  echo "Unexpected baseline acceptance" >&2; status=1
elif ! grep -F 'under_application' "$out/OrderedClosure.baseline.log"; then
  cat "$out/OrderedClosure.baseline.log" >&2; status=1
fi
# The file witness constructs the HasIO dictionary and invokes its selected
# methods before requesting argc. Only the runtime primitive is still missing
# at this frontier. A future implementation can also produce a checked image.
for target in linux-x86_64 netbsd-x86_64; do
  before="$out/file-baseline-$target.tsv"
  after="$out/file-candidate-$target.tsv"
  if ! grep -F $'result\tREJECTED\tunsupported_one_step_expression\t[__]' "$before"; then
    echo "Unexpected baseline file frontier: $target" >&2; status=1
  fi
  if ! grep -Fx $'result\tREJECTED\trecursive_call\tBinaryFilePrefix.main -> {{csegen:13}:0} -> System.{getArgs:17} -> Prelude.Types.rangeFromTo -> Prelude.Types.takeUntil -> Prelude.Types.takeUntil' "$after" &&
     ! grep -q $'^result\tCOMPILED_NOT_RUN\t' "$after"; then
    echo "Unexpected file frontier after dictionary application: $target" >&2; status=1
  fi
done
# Mutate the actual checked direct artifact, recompute its body digest, and
# verify semantic rejection (not checksum rejection). Never execute mutants.
python3 - "$out" <<'PY' || status=1
import hashlib
import re
import sys
from pathlib import Path
from backend.idric_x86 import (
    UnsupportedError, compile_checked_artifact, parse_checked_artifact_bytes, BODY_HEADER,
)
out = Path(sys.argv[1])
raw = (out / "OrderedDirect.one-step").read_text()
rows = raw.splitlines()
begin = rows.index("definitions_begin")
end = rows.index("definitions_end")
body = rows[begin+1:end]
changed = False
for i, line in enumerate(body):
    if line.startswith("OrderedDirect.main = "):
        body[i], count = re.subn(r"Prelude\.IO\.prim__putChar\(v[0-9]+,",
                                 "Prelude.IO.prim__putChar([__],", line, count=1)
        changed = count == 1
assert changed, "direct fixture must contain a native putChar call"
rows[begin+1:end] = body
rows[5] = "body_sha256\t" + hashlib.sha256((BODY_HEADER + "\n" + "\n".join(body) + "\n").encode()).hexdigest()
mutant = ("\n".join(rows) + "\n").encode()
(out / "negative-erased-character.MUTATED.one-step").write_bytes(mutant)
try:
    compile_checked_artifact(parse_checked_artifact_bytes(mutant))
except UnsupportedError as error:
    assert error.code == "observable_erased_value", error
    (out / "negative-erased-character.tsv").write_text("REJECTED\t" + str(error) + "\n")
else:
    raise AssertionError("observable erased character accepted")
PY
printf 'netbsd_native_execution\tNOT_RUN\nnative_file_operations\tNOT_VERIFIED\n' > "$out/boundary.tsv"
exit "$status"
