"""Run one real compiler-produced executable with independently supplied argument vectors."""

import platform
import subprocess
import sys
from pathlib import Path

from backend.idric_x86 import compile_artifact


def main(compiler_repository, output):
    if (platform.system(), platform.machine()) != ("Linux", "x86_64"):
        raise SystemExit("native process argument acceptance requires Linux x86-64")
    source = Path(__file__).resolve().parents[1] / "examples/autogenerated/process-arguments/ProcessArguments.idric"
    compiler = compiler_repository / "_/edric"
    output.mkdir(parents=True, exist_ok=True)
    artifacts = [output / f"process-{iteration}.one-step" for iteration in (1, 2)]
    for artifact in artifacts:
        subprocess.run([compiler, "--emit-one-step", source, "-o", artifact], check=True)
    assert artifacts[0].read_bytes() == artifacts[1].read_bytes(), "compiler handoff changed"

    for target in ("linux-x86_64", "netbsd-x86_64"):
        programs = [output / f"{target}-{iteration}.elf" for iteration in (1, 2)]
        for artifact, program in zip(artifacts, programs):
            compile_artifact(artifact, program, program.with_suffix(".listing"), source, target=target)
        assert programs[0].read_bytes() == programs[1].read_bytes(), target
        assert programs[0].with_suffix(".listing").read_bytes() == programs[1].with_suffix(".listing").read_bytes()
        header = subprocess.check_output(["readelf", "-h", "-l", "-n", programs[0]])
        assert b"Advanced Micro Devices X86-64" in header
        if target == "netbsd-x86_64":
            assert b"NetBSD" in header
            continue
        rows = ["case\targc\tstdout_hex\texit"]
        cases = [
            ("no-user-arguments", (), b"!-"),
            ("one-user-argument", ("zebra",), b"!-"),
            ("second-argument", ("first", "zebra"), b"!Y"),
            ("swapped", ("zebra", "first"), b"!N"),
            ("empty", ("zebra", ""), b"!N"),
            ("short", ("other", "zebr"), b"!N"),
            ("long", ("other", "zebraX"), b"!N"),
            ("non-ascii", ("other", "zèbra"), b"!N"),
            ("extra-argument", ("first", "zebra", "third"), b"!-"),
        ]
        for label, arguments, expected in cases:
            run = subprocess.run([programs[0], *arguments], capture_output=True, timeout=5)
            assert (run.stdout, run.stderr, run.returncode) == (expected, b"", 0), (label, run)
            rows.append(f"{label}\t{1 + len(arguments)}\t{run.stdout.hex()}\t{run.returncode}")
        (output / "native-arguments.tsv").write_text("\n".join(rows) + "\n")
        print("\n".join(rows))


if __name__ == "__main__":
    main(Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve())
